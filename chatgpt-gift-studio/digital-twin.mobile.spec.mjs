import { test, expect } from "@playwright/test";
test("mobile digital twin feedback and reset", async ({ browser }) => {
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await page.goto(process.env.TARGET_BASE||"https://aperture-gift-studio.onrender.com/",{waitUntil:"domcontentloaded"});
 await expect(page.locator("#digitalTwin")).toBeVisible();
 await page.locator("#twinInterest").selectOption("beauty");
 await page.locator("#runTwin").click();
 await expect(page.locator("#twinOutput")).toBeVisible();
 await expect(page.locator("#twinOutput")).toContainText("Simulated top matches");
 await page.getByRole("button",{name:/More like this for/}).first().click();
 await expect(page.locator("#twinOutput")).toContainText("in-session feedback");
 await page.locator("#resetTwin").click();
 await expect(page.locator("#twinOutput")).toBeHidden();
 await expect(page.locator("#twinStyle")).toHaveValue("practical");
 await expect(page.locator("#twinInterest")).toHaveValue("beauty");
 await page.locator("#lessonCategory").selectOption("books");
 await expect(page.locator("#lessonCards")).toContainText("personalized book-and-reflection");
 await expect(page.locator("#lessonCards a[href='https://bookshop.org/']")).toBeVisible();
 await page.locator("#shopCategory").selectOption("beauty");
 await expect(page.locator("#shopCards")).toContainText("Ulta Beauty");
 await page.locator("#shopCards").getByRole("button",{name:"Free interactive tutorial"}).first().click();
 await expect(page.locator("#lessonCategory")).toHaveValue("beauty");
 await expect(page.locator("#lessonCards")).toContainText("thoughtful self-care gift");
 await page.close();
});

test("mobile free gift reveal, activity and pass-it-forward", async ({browser})=>{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const payload={recipient:"Friend",sender:"Someone",message:"You matter more than you know. Wishing you joy, love, and wonder.",feeling:"joy",occasion:"just-because"};
 const token=Buffer.from(JSON.stringify(payload)).toString("base64url");
 await page.goto((process.env.TARGET_BASE||"https://aperture-gift-studio.onrender.com/")+"/gift#"+token,{waitUntil:"domcontentloaded"});
 await expect(page.getByRole("button",{name:/Unwrap your gift/})).toBeVisible();
 await page.getByRole("button",{name:/Unwrap your gift/}).click();
 await expect(page.locator("#message")).toHaveText(payload.message);
 await page.locator("#moment").click();
 await expect(page.locator("#affirmation")).toContainText("Reach out");
 await page.locator("#nextName").fill("Alex");
 await page.locator("#nextSender").fill("Friend");
 await page.locator("#nextMessage").fill("Have a wonderful day.");
 await page.locator("#createNext").click();
 await expect(page.locator("#nextStatus")).not.toContainText("Add a name");
 await expect(page.locator("#revealed")).toBeVisible();
 await page.close();
});
